/** Permissions effectives d'un rôle, `*` résolu. */
export function permissionsForRole(role: RoleDefinition): readonly PermissionCode[] {
  return role.permissions === '*' ? PERMISSION_CODES : role.permissions;
}

export function findRole(code: string): RoleDefinition | undefined {
  return ROLES.find((role) => role.code === code);
}
